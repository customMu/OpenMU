/// <summary>
/// The price of enchanting by rank (09.10.2026, wiki §7). Jewel of Bless / Soul: price ranks 3..8 take 1, 2, 3, 4, 5, 6
/// jewels of the stack per level; ranks 1 and 2: 1 Bless gives +3 / +2 levels, 1 Soul one level. Chaos Machine
/// +10..+15: the Bless and Soul of the mix x1 (ranks 1-3), x2 (4-5), x3 (6-8). The first sets of a rank (Dragon,
/// Guardian, Dark Phoenix, Valiant, Glorious) have the price of the rank before. Items without a rank: 1 jewel per level,
/// x1. The client has the same (GameLogic/Items/EnchantPrice.h); the table is generated by tools/balance/enchant_price.py.
/// </summary>
public static class EnchantPriceRanks
