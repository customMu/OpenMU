    /// <summary>
    /// Gets the rank of the price of the item (0 without a rank).
    /// </summary>
    /// <param name="definition">The item definition.</param>
    /// <returns>The rank of the price, 0..8.</returns>
    public static int GetPriceRank(ItemDefinition? definition)
    {
        return definition is not null && PriceRanks.TryGetValue((definition.Group, definition.Number), out var rank) ? rank : 0;
    }

    /// <summary>
    /// Gets the jewels which one use of a Jewel of Bless or Soul takes from the stack, and the levels it gives.
    /// </summary>
    /// <param name="definition">The definition of the enchanted item.</param>
    /// <param name="soul"><c>true</c> for the Jewel of Soul.</param>
    /// <returns>The jewels and the levels.</returns>
    public static (int Jewels, int Levels) GetStep(ItemDefinition? definition, bool soul)
    {
        var rank = GetPriceRank(definition);
        if (rank <= 2)
        {
            return (1, soul || rank == 0 ? 1 : 4 - rank);
        }

        return (rank - 2, 1);
    }

    /// <summary>
    /// Gets the multiplier of the Bless and Soul of the Chaos Machine mixes +10..+15.
    /// </summary>
    /// <param name="definition">The definition of the item of the mix.</param>
    /// <returns>1, 2 or 3.</returns>
    public static int GetChaosMachineMultiplier(ItemDefinition? definition)
    {
        var rank = GetPriceRank(definition);
        return rank >= 6 ? 3 : rank >= 4 ? 2 : 1;
    }

